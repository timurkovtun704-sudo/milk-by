-- =========================================================
-- Миграция: SEO-метаданные и перенаправления
-- =========================================================

BEGIN;

-- ---------------------------------------------------------
-- 1. SEO-метаданные страниц, товаров и новостей
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.seo_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Тип объекта: обычная страница, товар или новость
    entity_type VARCHAR(20) NOT NULL,

    -- ID товара или новости.
    -- Для обычных страниц должен быть NULL.
    entity_id BIGINT,

    -- Язык SEO-записи
    language_code VARCHAR(2) NOT NULL,

    -- Полный локализованный путь, например /ru/products/milk
    path TEXT NOT NULL,

    -- Общий UUID для SEO-записей одной страницы на разных языках
    translation_group UUID NOT NULL DEFAULT gen_random_uuid(),

    -- SEO-метаданные
    title VARCHAR(200) NOT NULL,
    description VARCHAR(500) NOT NULL,
    h1 VARCHAR(200) NOT NULL,

    -- Канонический адрес
    canonical_url TEXT,

    -- Open Graph
    og_title VARCHAR(200),
    og_description VARCHAR(500),
    og_image_url TEXT,

    -- Индексация поисковыми системами
    is_indexable BOOLEAN NOT NULL DEFAULT TRUE,
    is_followable BOOLEAN NOT NULL DEFAULT TRUE,

    -- Публикация SEO-записи
    is_published BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Допустимые типы объектов
    CONSTRAINT seo_entries_entity_type_check
        CHECK (entity_type IN ('page', 'product', 'news')),

    -- Допустимые языки
    CONSTRAINT seo_entries_language_check
        CHECK (language_code IN ('ru', 'be', 'en', 'zh')),

    -- Для страниц entity_id не используется.
    -- Для товаров и новостей ID обязателен.
    CONSTRAINT seo_entries_entity_id_check
        CHECK (
            (entity_type = 'page' AND entity_id IS NULL)
            OR
            (entity_type IN ('product', 'news')
                AND entity_id IS NOT NULL
                AND entity_id > 0)
        ),

    -- Путь должен начинаться с соответствующего языка
    CONSTRAINT seo_entries_path_check
        CHECK (
            path ~ ('^/' || language_code || '(/|$)')
            AND path !~ '[?#[:space:]]'
            AND path NOT LIKE '//%'
        ),

    -- SEO-поля не должны быть пустыми
    CONSTRAINT seo_entries_title_check
        CHECK (LENGTH(TRIM(title)) > 0),

    CONSTRAINT seo_entries_description_check
        CHECK (LENGTH(TRIM(description)) > 0),

    CONSTRAINT seo_entries_h1_check
        CHECK (LENGTH(TRIM(h1)) > 0),

    -- Канонический URL, если указан, не должен быть пустым
    CONSTRAINT seo_entries_canonical_check
        CHECK (
            canonical_url IS NULL
            OR LENGTH(TRIM(canonical_url)) > 0
        )
);

-- Один путь на одном языке может принадлежать только одной записи
CREATE UNIQUE INDEX IF NOT EXISTS seo_entries_language_path_uidx
    ON public.seo_entries (language_code, path);

-- Один товар или одна новость могут иметь только одну SEO-запись
-- на конкретном языке
CREATE UNIQUE INDEX IF NOT EXISTS seo_entries_entity_language_uidx
    ON public.seo_entries (entity_type, entity_id, language_code)
    WHERE entity_id IS NOT NULL;

-- Одна языковая версия в рамках группы переводов
CREATE UNIQUE INDEX IF NOT EXISTS seo_entries_translation_language_uidx
    ON public.seo_entries (translation_group, language_code);

-- Быстрый поиск опубликованных записей
CREATE INDEX IF NOT EXISTS seo_entries_published_path_idx
    ON public.seo_entries (path)
    WHERE is_published = TRUE;

-- Поиск SEO-записей конкретного объекта
CREATE INDEX IF NOT EXISTS seo_entries_entity_idx
    ON public.seo_entries (entity_type, entity_id);

-- Поиск опубликованных индексируемых страниц
CREATE INDEX IF NOT EXISTS seo_entries_sitemap_idx
    ON public.seo_entries (updated_at DESC)
    WHERE is_published = TRUE
      AND is_indexable = TRUE;


-- ---------------------------------------------------------
-- 2. Таблица 301-перенаправлений
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.seo_redirects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    language_code VARCHAR(2) NOT NULL,

    -- Старый путь
    source_path TEXT NOT NULL,

    -- Новый путь
    destination_path TEXT NOT NULL,

    -- На данном этапе поддерживается постоянное перенаправление
    status_code SMALLINT NOT NULL DEFAULT 301,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT seo_redirects_language_check
        CHECK (language_code IN ('ru', 'be', 'en', 'zh')),

    CONSTRAINT seo_redirects_status_check
        CHECK (status_code = 301),

    CONSTRAINT seo_redirects_source_check
        CHECK (
            source_path ~ ('^/' || language_code || '(/|$)')
            AND source_path !~ '[?#[:space:]]'
            AND source_path NOT LIKE '//%'
        ),

    CONSTRAINT seo_redirects_destination_check
        CHECK (
            destination_path ~ ('^/' || language_code || '(/|$)')
            AND destination_path !~ '[?#[:space:]]'
            AND destination_path NOT LIKE '//%'
        ),

    CONSTRAINT seo_redirects_not_self_check
        CHECK (source_path <> destination_path)
);

-- Один старый путь на одном языке — одно перенаправление
CREATE UNIQUE INDEX IF NOT EXISTS seo_redirects_source_uidx
    ON public.seo_redirects (language_code, source_path);

-- Быстрый поиск активных перенаправлений
CREATE INDEX IF NOT EXISTS seo_redirects_active_source_idx
    ON public.seo_redirects (source_path)
    WHERE is_active = TRUE;


-- ---------------------------------------------------------
-- 3. Автоматическое обновление updated_at
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS seo_entries_updated_at_trigger
    ON public.seo_entries;

CREATE TRIGGER seo_entries_updated_at_trigger
    BEFORE UPDATE ON public.seo_entries
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS seo_redirects_updated_at_trigger
    ON public.seo_redirects;

CREATE TRIGGER seo_redirects_updated_at_trigger
    BEFORE UPDATE ON public.seo_redirects
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_at();


-- ---------------------------------------------------------
-- 4. Row Level Security
-- ---------------------------------------------------------

ALTER TABLE public.seo_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.seo_redirects ENABLE ROW LEVEL SECURITY;

-- Публичный доступ к таблицам напрямую не открываем.
-- Backend использует серверный Supabase Service Role Key.
-- Публичные и административные операции выполняются через API.


-- ---------------------------------------------------------
-- 5. Комментарии к таблицам и полям
-- ---------------------------------------------------------

COMMENT ON TABLE public.seo_entries IS
    'SEO-метаданные страниц, товаров и новостей сайта';

COMMENT ON TABLE public.seo_redirects IS
    'Постоянные 301-перенаправления старых URL на новые';

COMMENT ON COLUMN public.seo_entries.translation_group IS
    'Объединяет языковые версии одной страницы';

COMMENT ON COLUMN public.seo_entries.is_indexable IS
    'Разрешает или запрещает индексацию страницы поисковиками';

COMMENT ON COLUMN public.seo_entries.is_followable IS
    'Разрешает или запрещает переход поисковых роботов по ссылкам';

COMMENT ON COLUMN public.seo_entries.is_published IS
    'Определяет, доступна ли SEO-запись публичной части сайта';

COMMENT ON COLUMN public.seo_redirects.status_code IS
    'HTTP-код перенаправления. Поддерживается 301';

COMMIT;